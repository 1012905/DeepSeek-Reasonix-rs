const sorted = (keys: object) => Object.keys(keys).sort();

describe("wire parity", () => {
  it("kind sets agree in both directions", () => {
    expect([...wire.KINDS].sort()).toEqual([...manifest.kinds].sort());
  });

  it("every manifest type has a witness", () => {
    for (const key of Object.keys(manifest.types)) {
      const w = WITNESSES.find((x) => x.key === key);
      expect(w, `manifest type ${key} has no TS witness`).toBeDefined();
    }
  });

  for (const w of WITNESSES) {
    it(`${w.key}: full witness covers exactly the manifest fields`, () => {
      const t = manifest.types[w.key];
      expect(t, `${w.key} is not in the manifest`).toBeDefined();
      expect(sorted(w.full), w.key).toEqual([...t.fields].sort());
    });
  }

  for (const w of WITNESSES) {
    it(`${w.key}: required witness covers exactly the non-omitempty fields`, () => {
      const t = manifest.types[w.key];
      const omit = new Set(t.omitted);
      const required = t.fields.filter((f) => !omit.has(f)).sort();
      expect(sorted(w.req), w.key).toEqual(required);
    });
  }
});
